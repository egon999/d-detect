"""
Builds the Hindi meeting fixture, which is the only fixture that can test the product's promise.

## Why this exists at all

The app's headline promise is that a meeting held in Hindi comes back in Hindi — the words, the
action items, the summary, all of it. That promise rests on one decision in the transcriber:
`transcribe()` sends the recording to the model with **no language parameter**, so the language is
whatever the model hears rather than whatever the server guessed. Nothing in the test suite can
test that decision, because every test of the pipeline stubs the network boundary, and the fixture
that does reach the real model has only ever contained English speech.

`make-meeting-audio.mjs` documents the gap honestly: it can prove the pipeline and not the promise,
because the voices installed on this machine are en-US only. That was true of the Windows speech
synthesiser it used. It is not true of the machine as a whole — `piper`, a small neural
text-to-speech engine, runs here and has Hindi voices. So the gap is closable, and this closes it.

## What it produces

`meeting-hi.wav` — a two-voice Hindi conversation between a shopkeeper and his supplier, covering
the same ground as the English fixture so the two can be compared: a price that went up, a deal
actually agreed, two spoken deadlines, and one unresolved complaint. Deliberately a conversation
and not a monologue: the language the model reports is one thing, but the reading has to attribute
an action item to one speaker rather than the other, and a single voice would never catch that.

It is committed, so nobody has to run this to use the fixture. The script is here so the fixture
can be rebuilt, extended or re-recorded, and so what is on disk is reproducible rather than a
binary of unknown provenance.

## Why it is not part of the Node generator

Everything else in this directory is generated by `make-meeting-audio.mjs` under Node, and this is
Python. That is not a preference: `piper` is distributed as a Python package, the small Hindi voice
is a 63 MB ONNX model rather than something the language model can be cajoled into producing, and
Node has no text-to-speech engine on this machine at all. One fixture needs a different tool, and
pretending otherwise would mean not having the fixture.

Run: python .fixtures/make-meeting-audio-hi.py
"""

import json
import os
import shutil
import struct
import subprocess
import sys
import tempfile
import urllib.request
import wave

HERE = os.path.dirname(os.path.abspath(__file__))

# Whisper resamples to 16 kHz internally, so anything above it is bytes a person on a slow
# connection would pay to upload twice for no change in what comes back. piper synthesises at
# 22.05 kHz, which is why the bytes below are resampled down rather than left alone.
TARGET_RATE = 16_000

VOICE_BASE = "https://huggingface.co/rhasspy/piper-voices/resolve/main/hi/hi_IN"

# Two voices, because the meeting is a conversation. `pratham` is the shopkeeper and `priyamvada`
# the supplier, matching the English fixture's David/Zira split so the two read the same way.
VOICES = {
    "shopkeeper": ("pratham", "hi_IN-pratham-medium"),
    "supplier": ("priyamvada", "hi_IN-priyamvada-medium"),
}

# The meeting, in the words the two of them would actually use.
#
# Written to be worth extracting from rather than merely audible, the same way the English script
# is: three rupee figures so the summary's arithmetic has something real to be checked against, a
# quarter that is not a figure at all (25 बोरी, 2,400 रुपये, 2,650 रुपये) so `figuresIn` has both
# kinds of number to get right, a decision actually reached, two deadlines spoken the way they are
# spoken in a room — "गुरुवार की सुबह", "शुक्रवार तक" — and one thing nobody resolved, so the
# attention list has a genuine item.
#
# The dates are relative on purpose. A fixture naming an absolute date would only ever exercise the
# path where the model copied a date through; the anchoring rule and the weekday repair are both
# about a deadline counted from the day of the meeting, and that is what this produces.
SCRIPT = [
    ("shopkeeper", "संजय, चावल के ऑर्डर के बारे में। पिछले महीने तुमने मुझसे ढाई हजार रुपये प्रति बोरी लिए थे, "
                   "और इस महीने बिल में दो हजार छह सौ पचास लिखा है।"),
    ("supplier", "मिल ने सितंबर में भाव बढ़ा दिया है, रवि। अगर तुम चालीस बोरी लो तो मैं ढाई हजार रुपये प्रति बोरी "
                 "पर टिका रह सकता हूँ।"),
    ("shopkeeper", "चालीस बोरी मेरे गोदाम में नहीं आएँगी। तीस बोरी कर दो ढाई हजार पर, और आधा पैसा डिलीवरी पर दे दूँगा।"),
    ("supplier", "ठीक है। तीस बोरी ढाई हजार रुपये में, गुरुवार की सुबह डिलीवरी। बाकी पैसा तुम शुक्रवार तक भेज देना।"),
    ("shopkeeper", "एक बात और। पिछली डिलीवरी दो बोरी कम थी और किसी ने उसका हिसाब नहीं लगाया। वह इस बिल से काट दो।"),
    ("supplier", "मैं चालान देखकर गुरुवार से पहले सुधरा हुआ बिल भेज दूँगा।"),
]


def voice_paths(model: str, scratch: str) -> tuple[str, str]:
    """The model and its config, downloaded once and reused across runs.

    Kept out of the repository on purpose: one voice is 63 MB, which is not a fixture, and a voice
    is a general-purpose tool rather than something this project owns. The *fixture* is committed;
    the means of producing it is fetched, which is the difference between a large binary in the
    repo and a build step anybody can repeat.

    Cached under the system temp directory rather than in `scratch`, because `scratch` is removed
    at the end of every run and a 126 MB download repeated on each rebuild is a build step nobody
    will run twice.
    """
    cache = os.path.join(tempfile.gettempdir(), "detact-piper-voices")
    os.makedirs(cache, exist_ok=True)
    onnx = os.path.join(cache, f"{model}.onnx")
    config = os.path.join(cache, f"{model}.onnx.json")
    tier = model.split("-")[1]
    for url, target in ((f"{VOICE_BASE}/{tier}/medium/{model}.onnx", onnx),
                        (f"{VOICE_BASE}/{tier}/medium/{model}.onnx.json", config)):
        if os.path.exists(target):
            continue
        print(f"downloading {os.path.basename(url)} …", file=sys.stderr)
        urllib.request.urlretrieve(url, target)
    return onnx, config


def read_wav(path: str) -> tuple[int, list[int]]:
    with wave.open(path, "rb") as handle:
        raw = handle.readframes(handle.getnframes())
    return handle.getframerate(), list(struct.unpack(f"<{len(raw) // 2}h", raw))


def write_wav(path: str, rate: int, samples: list[int]) -> None:
    """16-bit mono PCM, written through `wave` rather than by hand.

    `make-meeting-audio.mjs` builds its RIFF bytes by hand because Node has nothing that writes a
    WAV. Python does, and using it means the size fields cannot disagree with the data — which is
    the one failure this fixture's sibling `meeting-truncated.wav` exists to produce on purpose.

    Samples are packed through `struct` and not written one at a time. The first version of this
    did `int(value).to_bytes(2, "little", signed=True)` inside a comprehension and produced a
    recording 91 seconds long with a peak amplitude of 255 — an empty room with a faint hiss on
    it, which is a fixture that would have "proved" the pipeline works while every reading of it
    was of nothing at all.
    """
    with wave.open(path, "wb") as handle:
        handle.setnchannels(1)
        handle.setsampwidth(2)
        handle.setframerate(rate)
        handle.writeframes(struct.pack(f"<{len(samples)}h", *samples))


def resample(samples: list[int], src_rate: int, dst_rate: int) -> list[int]:
    """Linear interpolation down to the target rate.

    Not the highest-quality resampler in existence and not meant to be: it is a ratio of about
    1.38, the input is already band-limited by the synthesiser, and the thing on the other end is a
    speech recogniser that resamples again. What matters is that the header states the true rate,
    because `measuredDurationMs` reads that number and a fixture lying about it would be a fixture
    testing a lie.
    """
    if src_rate == dst_rate:
        return samples
    count = int(len(samples) * dst_rate / src_rate)
    out = [0] * count
    step = src_rate / dst_rate
    for index in range(count):
        at = index * step
        low = int(at)
        high = min(low + 1, len(samples) - 1)
        frac = at - low
        out[index] = int(samples[low] * (1 - frac) + samples[high] * frac)
    return out


def render(scratch: str) -> list[int]:
    """Every line, through the voice that speaks it, joined into one recording."""
    combined: list[int] = []
    rate = TARGET_RATE
    for speaker, line in SCRIPT:
        _, model = VOICES[speaker]
        onnx, config = voice_paths(model, scratch)
        text = os.path.join(scratch, f"{speaker}.txt")
        spoken = os.path.join(scratch, f"{speaker}.wav")
        with open(text, "w", encoding="utf-8") as handle:
            handle.write(line + "\n")
        subprocess.run(
            [sys.executable, "-m", "piper", "--model", onnx, "--config", config,
             "--input-file", text, "--output-file", spoken],
            check=True,
        )
        rate, samples = read_wav(spoken)
        # A beat between speakers, so the two voices do not run into each other. A tenth of a
        # second is what a room sounds like between one person finishing and the next starting,
        # and a gap of zero is not a conversation anybody recorded.
        combined.extend(samples)
        combined.extend([0] * int(rate * 0.1))
    return resample(combined, rate, TARGET_RATE)


def main() -> None:
    if shutil.which("node") is None:
        print("node is missing, which this does not need but the rest of .fixtures does.", file=sys.stderr)
    try:
        import piper  # noqa: F401
    except ImportError:
        print(
            "piper is not installed, so the Hindi fixture cannot be built.\n"
            "  python -m pip install piper-tts\n"
            "The committed meeting-hi.wav is what the suite uses; this only rebuilds it.",
            file=sys.stderr,
        )
        raise SystemExit(1)

    scratch = tempfile.mkdtemp(prefix="detact-hi-fixture-")
    try:
        frames = render(scratch)
    finally:
        shutil.rmtree(scratch, ignore_errors=True)

    target = os.path.join(HERE, "meeting-hi.wav")
    write_wav(target, TARGET_RATE, frames)
    seconds = len(frames) / TARGET_RATE
    print(f"meeting-hi.wav  {os.path.getsize(target)} bytes, {seconds:.1f}s of Hindi speech, "
          f"{len(SCRIPT)} turns")


if __name__ == "__main__":
    main()
