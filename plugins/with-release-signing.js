/**
 * Keeps release signing alive across `expo prebuild`.
 *
 * ## Why this exists
 *
 * `android/` is a generated directory and is gitignored, so anything edited inside it is
 * one `expo prebuild --clean` away from being gone. Release signing was configured by hand
 * in `android/app/build.gradle`, which meant the next prebuild would silently put the
 * project back on the stock debug key — and a release APK signed with the debug key is one
 * anybody can unpack, modify and re-sign, because that key and its password ('android')
 * ship with the Android SDK.
 *
 * Silently is the dangerous word. Nothing fails, nothing warns; the APK just builds with a
 * different certificate, Google Sign-In starts returning DEVELOPER_ERROR because the SHA-1
 * registered in Firebase no longer matches, and the cause is three steps removed from the
 * symptom.
 *
 * ## How it works
 *
 * On every prebuild this plugin restores the keystore and its credentials from
 * `.keystore-backup/` (which is outside `android/`, so prebuild cannot reach it) and
 * rewrites the Gradle signing config to point at them.
 *
 * ## What is not in here
 *
 * No password and no key. Both come from `.keystore-backup/keystore.properties`, which is
 * gitignored. This file is committed, so a credential written here would be published.
 * When the backup is absent — a fresh clone, or CI without the secrets — the plugin leaves
 * the project on debug signing rather than failing the build, so somebody who just wants to
 * run the app can.
 */

const fs = require('fs');
const path = require('path');

const { withDangerousMod } = require('expo/config-plugins');

const BACKUP_DIR = '.keystore-backup';
const KEYSTORE_FILE = 'ddetect-release.jks';
const PROPERTIES_FILE = 'keystore.properties';

/**
 * The signing block, written into `android/app/build.gradle` in place of the template's.
 *
 * Guarded on the properties file existing so the generated Gradle is still valid on a
 * machine without the key.
 */
const SIGNING_CONFIGS = `    signingConfigs {
        debug {
            storeFile file('debug.keystore')
            storePassword 'android'
            keyAlias 'androiddebugkey'
            keyPassword 'android'
        }
        // Generated by plugins/with-release-signing.js. Credentials are read from
        // android/keystore.properties, which is restored from .keystore-backup/ on every
        // prebuild and is never committed.
        release {
            def props = new Properties()
            def propsFile = rootProject.file('keystore.properties')
            if (propsFile.exists()) {
                propsFile.withInputStream { props.load(it) }
                storeFile file(props['storeFile'])
                storePassword props['storePassword']
                keyAlias props['keyAlias']
                keyPassword props['keyPassword']
            }
        }
    }`;

const RELEASE_SIGNING_LINE = `            signingConfig rootProject.file('keystore.properties').exists() ? signingConfigs.release : signingConfigs.debug`;

/** Replaces the `signingConfigs { ... }` block, matching to its closing brace by depth. */
function replaceSigningConfigs(gradle) {
  const start = gradle.indexOf('    signingConfigs {');
  if (start === -1) return gradle;

  let depth = 0;
  let end = -1;
  for (let i = gradle.indexOf('{', start); i < gradle.length; i += 1) {
    if (gradle[i] === '{') depth += 1;
    else if (gradle[i] === '}') {
      depth -= 1;
      if (depth === 0) {
        end = i + 1;
        break;
      }
    }
  }
  if (end === -1) return gradle;
  return gradle.slice(0, start) + SIGNING_CONFIGS + gradle.slice(end);
}

/**
 * Points the `release` build type at the release signing config.
 *
 * The template emits `signingConfig signingConfigs.debug` inside both build types, so the
 * match is anchored on the `release {` that follows the debug block rather than on the
 * assignment alone — replacing every occurrence would also rewrite debug signing.
 */
function pointReleaseAtReleaseKey(gradle) {
  const marker = gradle.indexOf('        release {', gradle.indexOf('    buildTypes {'));
  if (marker === -1) return gradle;

  const assignment = gradle.indexOf('signingConfig signingConfigs.debug', marker);
  if (assignment === -1) return gradle;

  const lineStart = gradle.lastIndexOf('\n', assignment) + 1;
  const lineEnd = gradle.indexOf('\n', assignment);
  return gradle.slice(0, lineStart) + RELEASE_SIGNING_LINE + gradle.slice(lineEnd);
}

const withReleaseSigning = (config) =>
  withDangerousMod(config, [
    'android',
    (modConfig) => {
      const projectRoot = modConfig.modRequest.projectRoot;
      const androidRoot = modConfig.modRequest.platformProjectRoot;

      const backupKeystore = path.join(projectRoot, BACKUP_DIR, KEYSTORE_FILE);
      const backupProperties = path.join(projectRoot, BACKUP_DIR, PROPERTIES_FILE);

      if (!fs.existsSync(backupKeystore) || !fs.existsSync(backupProperties)) {
        // No key on this machine. Leave the template alone: debug signing still produces a
        // runnable app, and failing here would block anyone who only wants to run it.
        console.warn(
          '[with-release-signing] No .keystore-backup found — release builds will use the debug key.',
        );
        return modConfig;
      }

      fs.copyFileSync(backupKeystore, path.join(androidRoot, 'app', KEYSTORE_FILE));
      fs.copyFileSync(backupProperties, path.join(androidRoot, PROPERTIES_FILE));

      const gradlePath = path.join(androidRoot, 'app', 'build.gradle');
      const original = fs.readFileSync(gradlePath, 'utf8');
      const patched = pointReleaseAtReleaseKey(replaceSigningConfigs(original));
      if (patched !== original) fs.writeFileSync(gradlePath, patched);

      return modConfig;
    },
  ]);

module.exports = withReleaseSigning;
